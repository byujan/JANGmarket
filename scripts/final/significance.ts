#!/usr/bin/env tsx
/**
 * How much of the final-project results is signal?
 *
 *   tsx scripts/final/significance.ts            # fresh seeds (the headline)
 *   tsx scripts/final/significance.ts --all      # all three seeds
 *
 * Every arm runs on the same markets (same seed, case, index), so every
 * comparison here is paired, market by market:
 *
 * - closing rate: exact McNemar test on the markets where the arms disagree
 * - efficiency of closed deals: markets both arms closed; mean difference with
 *   a bootstrap 95% CI, and an exact sign test
 * - realised efficiency: every feasible market, a failed negotiation counting
 *   as 0. This one is immune to the arms closing different markets, which
 *   biases the closed-deal comparison
 * - buyer share: markets both arms closed, as for efficiency
 *
 * Reads results/final/*.json; writes results/final/SIGNIFICANCE.md. Bootstrap
 * resampling uses a fixed seed, so the output is reproducible.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { mulberry32 } from "../hw7/lib.ts";

const DIR = "results/final";
const SEEDS = process.argv.includes("--all") ? [20261028, 20261101, 20261102] : [20261101, 20261102];
const BASE = "fix";
const ARMS = ["fix+meso", "fix+disclose", "fix+disclose1", "fix+meso+disclose", "fix+meso+disclose1", "fix+option2"];
const CASES = ["ordinary", "asymmetric"];
const B = 10_000;

type Quality = { efficiency: number; buyerShare: number };
type Condition = { agreed: boolean; q?: Quality };
type Row = { case: string; index: number; feasible: boolean; jang: Condition; priceOnly: Condition };
type Market = { key: string; row: Row };

function load(variant: string): Map<string, Row> {
  const out = new Map<string, Row>();
  for (const seed of SEEDS) {
    const file = `${DIR}/${variant}-seed${seed}.json`;
    if (!readdirSync(DIR).includes(`${variant}-seed${seed}.json`)) throw new Error(`missing ${file}; run the arm first`);
    const data = JSON.parse(readFileSync(file, "utf8")) as { rows: Row[] };
    for (const row of data.rows) out.set(`${seed}:${row.case}:${row.index}`, row);
  }
  return out;
}

// ---------------------------------------------------------------- statistics

function binomTwoSided(k: number, n: number): number {
  if (n === 0) return 1;
  const pmf = (i: number) => {
    let logC = 0;
    for (let j = 1; j <= i; j += 1) logC += Math.log(n - i + j) - Math.log(j);
    return Math.exp(logC - n * Math.LN2);
  };
  const observed = pmf(k);
  let p = 0;
  for (let i = 0; i <= n; i += 1) if (pmf(i) <= observed + 1e-12) p += pmf(i);
  return Math.min(1, p);
}

const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / xs.length;

function bootstrapCI(diffs: number[], seed = 665): [number, number] {
  if (diffs.length === 0) return [NaN, NaN];
  const rng = mulberry32(seed);
  const means: number[] = [];
  for (let b = 0; b < B; b += 1) {
    let total = 0;
    for (let i = 0; i < diffs.length; i += 1) total += diffs[Math.floor(rng() * diffs.length)];
    means.push(total / diffs.length);
  }
  means.sort((a, b) => a - b);
  return [means[Math.floor(0.025 * B)], means[Math.floor(0.975 * B)]];
}

function paired(diffs: number[]) {
  const up = diffs.filter((d) => d > 1e-9).length;
  const down = diffs.filter((d) => d < -1e-9).length;
  return { n: diffs.length, mean: diffs.length ? mean(diffs) : NaN, ci: bootstrapCI(diffs), up, down, p: binomTwoSided(up, up + down) };
}

// ---------------------------------------------------------------- comparisons

const f = (x: number, d = 3) => (Number.isFinite(x) ? (x >= 0 ? "+" : "") + x.toFixed(d) : "-");
const fp = (p: number) => (p < 0.001 ? "<0.001" : p.toFixed(3));
const ci = ([lo, hi]: [number, number]) => `[${f(lo)}, ${f(hi)}]`;
const excludesZero = ([lo, hi]: [number, number]) => lo > 0 || hi < 0;

const base = load(BASE);
const md: string[] = [
  "# Final-project arms: significance",
  "",
  `Generated by \`scripts/final/significance.ts\` from \`${DIR}\`, seeds ${SEEDS.join(", ")}. Every comparison is paired on identical markets against the \`${BASE}\` arm (the HW7 headline), or against price-only negotiation on the same markets. CIs are bootstrap 95% (${B.toLocaleString("en-US")} resamples, fixed seed); p-values are exact two-sided (McNemar for closing, sign test for the rest).`,
  "",
  `**Multiple comparisons.** This file runs ${ARMS.length * CASES.length * 4 + CASES.length * 2 * 2} tests. At a Bonferroni threshold that is p < ${(0.05 / (ARMS.length * CASES.length * 4 + CASES.length * 2 * 2)).toFixed(4)}; treat anything above it as suggestive, not shown.`,
  "",
];

for (const kind of CASES) {
  md.push(`## ${kind}`, "");
  md.push(
    `| arm vs \`${BASE}\` | close (arm / base, feasible) | McNemar: arm-only / base-only, p | eff. of closed deals: n, mean diff, 95% CI, up/down, p | realised eff. (fail = 0): mean diff, 95% CI, p | buyer share: mean diff, 95% CI, p |`,
  );
  md.push("| --- | --- | --- | --- | --- | --- |");
  for (const arm of ARMS) {
    const rows = load(arm);
    const markets: Market[] = [...base.entries()].filter(([, r]) => r.case === kind && r.feasible).map(([key, row]) => ({ key, row }));
    const pairs = markets.map(({ key, row }) => ({ b: row.jang, a: rows.get(key)!.jang }));

    const armOnly = pairs.filter((p) => p.a.agreed && !p.b.agreed).length;
    const baseOnly = pairs.filter((p) => !p.a.agreed && p.b.agreed).length;
    const closedArm = pairs.filter((p) => p.a.agreed).length;
    const closedBase = pairs.filter((p) => p.b.agreed).length;

    const both = pairs.filter((p) => p.a.agreed && p.b.agreed && p.a.q && p.b.q);
    const eff = paired(both.map((p) => p.a.q!.efficiency - p.b.q!.efficiency));
    const realised = paired(pairs.map((p) => (p.a.agreed ? p.a.q!.efficiency : 0) - (p.b.agreed ? p.b.q!.efficiency : 0)));
    const share = paired(both.map((p) => p.a.q!.buyerShare - p.b.q!.buyerShare));

    md.push(
      `| \`${arm}\` | ${closedArm} / ${closedBase} of ${pairs.length} | ${armOnly} / ${baseOnly}, p=${fp(binomTwoSided(armOnly, armOnly + baseOnly))} | ${eff.n}, ${f(eff.mean)}, ${ci(eff.ci)}${excludesZero(eff.ci) ? " *" : ""}, ${eff.up}/${eff.down}, p=${fp(eff.p)} | ${f(realised.mean)}, ${ci(realised.ci)}${excludesZero(realised.ci) ? " *" : ""}, p=${fp(realised.p)} | ${f(share.mean)}, ${ci(share.ci)}${excludesZero(share.ci) ? " *" : ""}, p=${fp(share.p)} |`,
    );
  }
  md.push("", "`*` = the 95% CI excludes zero.", "");

  // Against price-only: the HW7 Claim B question, for the base and the disclosure arm.
  md.push(`### JANG vs price-only on the same markets (${kind})`, "");
  md.push("| arm | markets both closed | JANG eff - price-only eff: mean, 95% CI, JANG better/worse, p | realised eff. (fail = 0): mean, 95% CI, p |");
  md.push("| --- | --- | --- | --- |");
  for (const arm of [BASE, "fix+disclose"]) {
    const rows = load(arm);
    const markets = [...rows.values()].filter((r) => r.case === kind && r.feasible);
    const both = markets.filter((r) => r.jang.agreed && r.priceOnly.agreed && r.jang.q && r.priceOnly.q);
    const eff = paired(both.map((r) => r.jang.q!.efficiency - r.priceOnly.q!.efficiency));
    const realised = paired(markets.map((r) => (r.jang.agreed ? r.jang.q!.efficiency : 0) - (r.priceOnly.agreed ? r.priceOnly.q!.efficiency : 0)));
    md.push(
      `| \`${arm}\` | ${eff.n} | ${f(eff.mean)}, ${ci(eff.ci)}${excludesZero(eff.ci) ? " *" : ""}, ${eff.up}/${eff.down}, p=${fp(eff.p)} | ${f(realised.mean)}, ${ci(realised.ci)}${excludesZero(realised.ci) ? " *" : ""}, p=${fp(realised.p)} |`,
    );
  }
  md.push("");
}

const out = `${DIR}/SIGNIFICANCE${process.argv.includes("--all") ? "-all-seeds" : ""}.md`;
writeFileSync(out, md.join("\n") + "\n");
console.log(md.join("\n"));
console.error(`wrote ${out}`);
